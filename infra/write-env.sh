#!/usr/bin/env bash
#
# Fill the web app's sync env from `terraform output` — no copy/pasting ids.
#
#   bash infra/write-env.sh            # local dev -> apps/web/.env.local
#   bash infra/write-env.sh deploy     # production build -> apps/web/.env.production.local
#
# Reads only Terraform *outputs* (no API calls, no credentials needed). An
# existing target file is backed up to <file>.bak first. Values written are not
# secrets (a public client id and URLs), but the files are git-ignored anyway.

set -euo pipefail

MODE="${1:-local}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INFRA="$ROOT/infra"
WEB="$ROOT/apps/web"

if ! command -v terraform >/dev/null 2>&1; then
  echo "error: terraform is not installed" >&2
  exit 1
fi

tf_output() {
  terraform -chdir="$INFRA" output -raw "$1" 2>/dev/null || true
}

need() { # value name
  if [ -z "$1" ]; then
    echo "error: terraform output '$2' is empty." >&2
    echo "       Run: terraform -chdir=infra apply" >&2
    exit 1
  fi
}

API_URL="$(tf_output api_url)";          need "$API_URL" api_url
AUTH_DOMAIN="$(tf_output cognito_domain)"; need "$AUTH_DOMAIN" cognito_domain
CLIENT_ID="$(tf_output cognito_client_id)"; need "$CLIENT_ID" cognito_client_id
APP_URL="$(tf_output app_url)";          need "$APP_URL" app_url

case "$MODE" in
  local)
    TARGET="$WEB/.env.local"
    REDIRECT="http://localhost:5173"
    BODY="$(cat <<EOF
# Generated by infra/write-env.sh (local dev) — safe to delete.
#
# The API is reached through the Vite dev proxy as /api so the session cookie
# stays first-party (a cross-site cookie would never be sent).
VITE_SYNC_API_BASE=/api
VITE_SYNC_PROXY_TARGET=$API_URL
VITE_SYNC_AUTH_AUTHORITY=$AUTH_DOMAIN
VITE_SYNC_AUTH_CLIENT_ID=$CLIENT_ID
VITE_SYNC_AUTH_REDIRECT_URI=$REDIRECT
EOF
)"
    ;;
  deploy)
    TARGET="$WEB/.env.production.local"
    REDIRECT="${APP_URL%/}/"
    BODY="$(cat <<EOF
# Generated by infra/write-env.sh (deploy) — safe to delete.
#
# Absolute API URL (the deployed app is not proxied). If the API is on a
# different site than the app, the session cookie will be blocked by the
# browser — use a same-site custom domain or a same-origin /api proxy.
VITE_SYNC_API_BASE=$API_URL
VITE_SYNC_AUTH_AUTHORITY=$AUTH_DOMAIN
VITE_SYNC_AUTH_CLIENT_ID=$CLIENT_ID
VITE_SYNC_AUTH_REDIRECT_URI=$REDIRECT
EOF
)"
    ;;
  *)
    echo "usage: bash infra/write-env.sh [local|deploy]" >&2
    exit 2
    ;;
esac

if [ -f "$TARGET" ]; then
  cp "$TARGET" "$TARGET.bak"
  echo "backed up existing $(basename "$TARGET") -> $(basename "$TARGET").bak"
fi

printf '%s\n' "$BODY" > "$TARGET"

echo "wrote $TARGET"
echo "  api url        : $API_URL"
echo "  auth authority : $AUTH_DOMAIN"
echo "  client id      : $CLIENT_ID"
echo "  redirect uri   : $REDIRECT"
echo "  app url        : $APP_URL"
